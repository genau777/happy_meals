#ifndef MODELS_H
#define MODELS_H

#include <QString>
#include <QUuid>
#include <QList>

///
/// \brief Категории ингредиентов.
///
/// Перечисление используется для группировки ингредиентов по типу:
/// овощи, мясо, рыба, молочные продукты, крупы и прочее.
///
enum class IngredientCategory {
    VEGETABLES,
    MEAT,
    FISH,
    DAIRY,
    GRAINS,
    OTHER
};

///
/// \brief Типы кухни.
///
/// Перечисление используется для указания кухни, к которой относится блюдо.
///
enum class CuisineType {
    JAPANESE,
    ITALIAN,
    RUSSIAN,
    CHINESE,
    MEXICAN,
    ANY
};

///
/// \brief Типы блюд.
///
/// Перечисление используется для классификации блюд по категории.
///
enum class DishType {
    FIRST_COURSE,
    SECOND_COURSE,
    SALAD,
    DESSERT,
    ANY
};

///
/// \brief Структура ингредиента.
///
/// Структура хранит данные об отдельном ингредиенте:
/// идентификатор, название и категорию.
///
/// На вход получает данные ингредиента при создании объекта.
/// На выходе используется как часть рецептов и пользовательских предпочтений.
///
struct Ingredient {
    QUuid id;                       ///< Уникальный идентификатор ингредиента.
    QString name;                   ///< Название ингредиента.
    IngredientCategory category;    ///< Категория ингредиента.

    ///
    /// \brief Сравнивает два ингредиента по идентификатору.
    /// \param other Ингредиент для сравнения.
    /// \return true, если идентификаторы совпадают, иначе false.
    ///
    bool operator==(const Ingredient& other) const { return id == other.id; }
};

///
/// \brief Структура блюда.
///
/// Структура хранит основную информацию о блюде:
/// название, кухню, тип, список ингредиентов и время приготовления.
///
/// На вход получает данные рецепта.
/// На выходе используется при подборе, фильтрации и отображении блюд.
///
struct Dish {
    QUuid id;                       ///< Уникальный идентификатор блюда.
    QString name;                   ///< Название блюда.
    CuisineType cuisine;            ///< Тип кухни.
    DishType type;                  ///< Тип блюда.
    QList<Ingredient> ingredients;  ///< Список ингредиентов блюда.

    int prepTime;                   ///< Время приготовления в минутах.
};

///
/// \brief Структура пользовательских предпочтений.
///
/// Структура хранит параметры, по которым выполняется подбор блюд:
/// любимые кухни, типы блюд, нежелательные ингредиенты и максимальное время приготовления.
///
/// На вход получает выбранные пользователем фильтры.
/// На выходе используется фильтрами для формирования списка подходящих блюд.
///
struct Preferences {
    QList<CuisineType> favoriteCuisines;       ///< Предпочитаемые кухни пользователя.
    QList<DishType> favoriteDishTypes;         ///< Предпочитаемые типы блюд.
    QList<Ingredient> dislikedIngredients;     ///< Нежелательные ингредиенты.
    int maxCookingTime;                        ///< Максимальное время приготовления в минутах, 0 — без ограничений.
};

#endif