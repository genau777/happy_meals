#ifndef FILTERS_H
#define FILTERS_H

#include "models.h"

///
/// \brief Базовый класс фильтрации блюд.
///
/// Класс задает общий интерфейс для всех фильтров,
/// которые применяются к списку блюд.
///
/// На вход получает список блюд.
/// На выходе возвращает список блюд после применения условий фильтрации.
///
class Filter
{
public:
    ///
    /// \brief Виртуальный деструктор базового фильтра.
    ///
    virtual ~Filter() = default;

    ///
    /// \brief Применяет фильтр к списку блюд.
    /// \param dishes Исходный список блюд.
    /// \return Отфильтрованный список блюд.
    ///
    virtual QList<Dish> apply(const QList<Dish>& dishes) = 0;
};

///
/// \brief Класс фильтрации блюд по исключаемым ингредиентам.
///
/// Класс удаляет из результата блюда, содержащие ингредиенты,
/// которые пользователь указал как нежелательные.
///
/// На вход получает список исключаемых ингредиентов.
/// На выходе возвращает список блюд без нежелательных ингредиентов.
///
class IngredientFilter : public Filter
{
private:
    QList<Ingredient> excluded; ///< Список исключаемых ингредиентов.

public:
    ///
    /// \brief Создает фильтр по ингредиентам.
    /// \param excludedIngredients Список ингредиентов, которые нужно исключить.
    ///
    IngredientFilter(const QList<Ingredient>& excludedIngredients);

    ///
    /// \brief Применяет фильтр по ингредиентам.
    /// \param dishes Исходный список блюд.
    /// \return Список блюд без исключаемых ингредиентов.
    ///
    QList<Dish> apply(const QList<Dish>& dishes) override;
};

///
/// \brief Класс фильтрации блюд по типу кухни.
///
/// Класс оставляет только блюда, которые относятся
/// к выбранным пользователем кухням.
///
/// На вход получает список выбранных кухонь.
/// На выходе возвращает список блюд, подходящих по кухне.
///
class CuisineFilter : public Filter
{
private:
    QList<CuisineType> cuisines; ///< Список выбранных кухонь.

public:
    ///
    /// \brief Создает фильтр по кухням.
    /// \param c Список выбранных кухонь.
    ///
    CuisineFilter(const QList<CuisineType>& c) : cuisines(c) {}

    ///
    /// \brief Применяет фильтр по кухне.
    /// \param dishes Исходный список блюд.
    /// \return Список блюд, подходящих по выбранной кухне.
    ///
    QList<Dish> apply(const QList<Dish>& dishes) override;
};

///
/// \brief Класс фильтрации блюд по времени приготовления.
///
/// Класс оставляет только те блюда, время приготовления которых
/// не превышает указанное пользователем ограничение.
///
/// На вход получает максимальное время приготовления в минутах.
/// На выходе возвращает список блюд, подходящих по времени.
///
class TimeFilter : public Filter
{
private:
    int maxTime; ///< Максимальное время приготовления в минутах.

public:
    ///
    /// \brief Создает фильтр по времени приготовления.
    /// \param maxMinutes Максимальное допустимое время приготовления в минутах.
    ///
    TimeFilter(int maxMinutes) : maxTime(maxMinutes) {}

    ///
    /// \brief Применяет фильтр по времени приготовления.
    /// \param dishes Исходный список блюд.
    /// \return Список блюд, подходящих по времени приготовления.
    ///
    QList<Dish> apply(const QList<Dish>& dishes) override;
};

///
/// \brief Класс управления фильтрами блюд.
///
/// Класс объединяет несколько фильтров и применяет их к списку блюд
/// на основе пользовательских предпочтений.
///
/// На вход получает список блюд и предпочтения пользователя.
/// На выходе возвращает итоговый список подходящих блюд.
///
class FilterManager
{
public:
    ///
    /// \brief Применяет все фильтры к списку блюд.
    /// \param dishes Исходный список блюд.
    /// \param prefs Предпочтения пользователя.
    /// \return Список блюд после применения всех фильтров.
    ///
    QList<Dish> applyAll(const QList<Dish>& dishes, const Preferences& prefs);
};

#endif